function [Ux, Uy, Uz, Txx, Tyy, Tzz, Tyz, Tzx, Txy, Ex, Ey, Ez, tEx, tEy, tEz] ...
    = PE_FDTD3D_3_homo(Ux, Uy, Uz, Txx, Tyy, Tzz, Tyz, Tzx, Txy, Ex, Ey, Ez, tEx, tEy, tEz ...
    , dtdx ...
    , nx, ny, nz, rate ...
    , e, is_model_normal, is_model_share) %#codegen

  %PE_FDTD3D この関数の概要をここに記述
  %FDTD
  Ux(2:nx, :, :) = Ux(2:nx, :, :) + dtdx.density_x .* ( ...
  (Txx(2:nx, :, :) - Txx(1:nx - 1, :, :)) + ...
    (Txy(2:nx, 2:ny + 1, 1:nz) - Txy(2:nx, 1:ny, 1:nz)) + ...
    (Tzx(2:nx, 1:ny, 2:nz + 1) - Tzx(2:nx, 1:ny, 1:nz)));

  Uy(:, 2:ny, :) = Uy(:, 2:ny, :) + dtdx.density_y .* ( ...
    (Txy(2:nx + 1, 2:ny, 1:nz) - Txy(1:nx, 2:ny, 1:nz)) + ...
    (Tyy(:, 2:ny, :) - Tyy(:, 1:ny - 1, :)) + ...
    (Tyz(1:nx, 2:ny, 2:nz + 1) - Tyz(1:nx, 2:ny, 1:nz)));

  Uz(:, :, 2:nz) = Uz(:, :, 2:nz) + dtdx.density_z .* ( ...
    (Tzx(2:nx + 1, 1:ny, 2:nz) - Tzx(1:nx, 1:ny, 2:nz)) + ...
    (Tyz(1:nx, 2:ny + 1, 2:nz) - Tyz(1:nx, 1:ny, 2:nz)) + ...
    (Tzz(:, :, 2:nz) - Tzz(:, :, 1:nz - 1)));

  Txx = Txx + ...
    dtdx.C11 .* (Ux(2:nx + 1, :, :) - Ux(1:nx, :, :)) + ...
    dtdx.C12 .* (Uy(:, 2:ny + 1, :) - Uy(:, 1:ny, :)) + ...
    dtdx.C13.* (Uz(:, :, 2:nz + 1) - Uz(:, :, 1:nz)) + ...
    - (e(1, 1) * (Ex(2:nx + 1, 2:ny + 1, 2:nz + 1) - tEx(2:nx + 1, 2:ny + 1, 2:nz + 1)) + ...
    e(2, 1) * (Ey(2:nx + 1, 2:ny + 1, 2:nz + 1) - tEy(2:nx + 1, 2:ny +1, 2:nz + 1)) + ...
    e(3, 1) * (Ez(2:nx + 1, 2:ny + 1, 2:nz + 1) - tEz(2:nx + 1, 2:ny + 1, 2:nz + 1)));

  Tyy = Tyy + ...
    dtdx.C12.* (Ux(2:nx + 1, :, :) - Ux(1:nx, :, :)) + ...
    dtdx.C11 .* (Uy(:, 2:ny + 1, :) - Uy(:, 1:ny, :)) + ...
    dtdx.C13.* (Uz(:, :, 2:nz + 1) - Uz(:, :, 1:nz)) + ...
    - (e(1, 2) * (Ex(2:nx + 1, 2:ny + 1, 2:nz + 1) - tEx(2:nx + 1, 2:ny + 1, 2:nz + 1)) + ...
    e(2, 2) * (Ey(2:nx + 1, 2:ny + 1, 2:nz + 1) - tEy(2:nx + 1, 2:ny + 1, 2:nz + 1)) + ...
    e(3, 2) * (Ez(2:nx + 1, 2:ny + 1, 2:nz + 1) - tEz(2:nx + 1, 2:ny + 1, 2:nz + 1)));

  Tzz =  Tzz + ...
    dtdx.C13 .* (Ux(2:nx + 1, :, :) - Ux(1:nx, :, :)) + ...
    dtdx.C13 .* (Uy(:, 2:ny + 1, :) - Uy(:, 1:ny, :)) + ...
    dtdx.C33 .* (Uz(:, :, 2:nz + 1) - Uz(:, :, 1:nz)) + ...
    - (e(1, 3) * (Ex(2:nx  +1, 2:ny +1, 2:nz + 1) - tEx(2:nx + 1, 2:ny + 1, 2:nz + 1)) + ...
    e(2, 3) * (Ey(2:nx + 1, 2:ny  + 1, 2:nz + 1) - tEy(2:nx + 1, 2:ny + 1, 2:nz + 1)) + ...
    e(3, 3) * (Ez(2:nx + 1, 2:ny + 1, 2:nz + 1) - tEz(2:nx + 1, 2:ny + 1, 2:nz + 1)));

  Tyz(2:nx, 2:ny, 2:nz) =  Tyz(2:nx, 2:ny, 2:nz) + dtdx.C44 .* ( ...
    (Uz(2:nx, 2:ny, 2:nz) - Uz(2:nx, 1:ny - 1, 2:nz)) + ...
    (Uy(2:nx, 2:ny, 2:nz) - Uy(2:nx, 2:ny, 1:nz - 1))) + ...
    - (e(1, 4) * (Ex(2:nx, 2:ny, 2:nz) - tEx(2:nx, 2:ny, 2:nz)) +e(2, 4) * (Ey(2:nx, 2:ny, 2:nz) - tEy(2:nx, 2:ny, 2:nz)) +e(3, 4) * (Ez(2:nx, 2:ny, 2:nz) - tEz(2:nx, 2:ny, 2:nz)));

  Tzx(2:nx, 2:ny, 2:nz) = Tzx(2:nx, 2:ny, 2:nz) + dtdx.C44 .* ( ...
    (Uz(2:nx, 2:ny, 2:nz) - Uz(1:nx - 1, 2:ny, 2:nz)) + ...
    (Ux(2:nx, 2:ny, 2:nz) - Ux(2:nx, 2:ny, 1:nz - 1))) + ...
    - (e(1, 5) * (Ex(2:nx, 2:ny, 2:nz) - tEx(2:nx, 2:ny, 2:nz)) +e(2, 5) * (Ey(2:nx, 2:ny, 2:nz) - tEy(2:nx, 2:ny, 2:nz)) +e(3, 5) * (Ez(2:nx, 2:ny, 2:nz) - tEz(2:nx, 2:ny, 2:nz)));

  Txy(2:nx, 2:ny, 2:nz) = Txy(2:nx, 2:ny, 2:nz) + dtdx.C66.* ( ...
    (Ux(2:nx, 2:ny, 2:nz) - Ux(2:nx, 1:ny - 1, 2:nz)) + ...
    (Uy(2:nx, 2:ny, 2:nz) - Uy(1:nx - 1, 2:ny, 2:nz))) + ...
    - (e(1, 6) * (Ex(2:nx, 2:ny, 2:nz) - tEx(2:nx, 2:ny, 2:nz)) +e(2, 6) * (Ey(2:nx, 2:ny, 2:nz) - tEy(2:nx, 2:ny, 2:nz)) +e(3, 6) * (Ez(2:nx, 2:ny, 2:nz) - tEz(2:nx, 2:ny, 2:nz)));




  tEx = Ex; tEy = Ey; tEz = Ez;

  Ex(2:nx, 2:ny, 2:nz) = (1 - rate.sigmaip) * Ex(2:nx, 2:ny, 2:nz) ...
    - dtdx.ip * is_model_share .* ( ...
    e(1, 1) * (Ux(3:nx + 1, 2:ny, 2:nz) - Ux(1:nx - 1, 2:ny, 2:nz)) + ...
    e(1, 2) * (Uy(2:nx, 3:ny + 1, 2:nz) - Uy(2:nx, 1:ny - 1, 2:nz)) + ...
    e(1, 3) * (Uz(2:nx, 2:ny, 3:nz + 1) - Uz(2:nx, 2:ny, 1:nz - 1)) + ...
    e(1, 4) / 2 * ((Uy(2:nx, 2:ny, 2:nz) - Uy(2:nx, 2:ny, 1:nz - 1)) + (Uz(2:nx, 2:ny, 2:nz) - Uz(2:nx, 1:ny - 1, 2:nz))) + ...
    e(1, 5) / 2 * ((Uz(2:nx, 2:ny, 2:nz) - Uz(1:nx - 1, 2:ny, 2:nz)) + (Ux(2:nx, 2:ny, 2:nz) - Ux(2:nx, 2:ny, 1:nz - 1))) + ...
    e(1, 6) / 2 * ((Ux(2:nx, 2:ny, 2:nz) - Ux(2:nx, 1:ny - 1, 2:nz)) + (Uy(2:nx, 2:ny, 2:nz) - Uy(1:nx - 1, 2:ny, 2:nz))));

  Ey(2:nx, 2:ny, 2:nz) = (1 - rate.sigmaip) * Ey(2:nx, 2:ny, 2:nz) ...
    - dtdx.ip * is_model_share .* ( ...
    e(2, 1) * (Ux(3:nx + 1, 2:ny, 2:nz) - Ux(1:nx - 1, 2:ny, 2:nz)) + ...
    e(2, 2) * (Uy(2:nx, 3:ny + 1, 2:nz) - Uy(2:nx, 1:ny - 1, 2:nz)) + ...
    e(2, 3) * (Uz(2:nx, 2:ny, 3:nz + 1) - Uz(2:nx, 2:ny, 1:nz - 1)) + ...
    e(2, 4) / 2 * ((Uy(2:nx, 2:ny, 2:nz) - Uy(2:nx, 2:ny, 1:nz - 1)) + (Uz(2:nx, 2:ny, 2:nz) - Uz(2:nx, 1:ny - 1, 2:nz))) + ...
    e(2, 5) / 2 * ((Uz(2:nx, 2:ny, 2:nz) - Uz(1:nx - 1, 2:ny, 2:nz)) + (Ux(2:nx, 2:ny, 2:nz) - Ux(2:nx, 2:ny, 1:nz - 1))) + ...
    e(2, 6) / 2 * ((Ux(2:nx, 2:ny, 2:nz) - Ux(2:nx, 1:ny - 1, 2:nz)) + (Uy(2:nx, 2:ny, 2:nz) - Uy(1:nx - 1, 2:ny, 2:nz))));

  Ez(2:nx, 2:ny, 2:nz) = (1 - rate.sigmaip) * Ez(2:nx, 2:ny, 2:nz) ...
    - dtdx.ip * is_model_share .* ( ...
    e(3, 1) * (Ux(3:nx + 1, 2:ny, 2:nz) - Ux(1:nx - 1, 2:ny, 2:nz)) + ...
    e(3, 2) * (Uy(2:nx, 3:ny + 1, 2:nz) - Uy(2:nx, 1:ny - 1, 2:nz)) + ...
    e(3, 3) * (Uz(2:nx, 2:ny, 3:nz + 1) - Uz(2:nx, 2:ny, 1:nz - 1)) + ...
    e(3, 4) / 2 * ((Uy(2:nx, 2:ny, 2:nz) - Uy(2:nx, 2:ny, 1:nz - 1)) + (Uz(2:nx, 2:ny, 2:nz) - Uz(2:nx, 1:ny - 1, 2:nz))) + ...
    e(3, 5) / 2 * ((Uz(2:nx, 2:ny, 2:nz) - Uz(1:nx - 1, 2:ny, 2:nz)) + (Ux(2:nx, 2:ny, 2:nz) - Ux(2:nx, 2:ny, 1:nz - 1))) + ...
    e(3, 6) / 2 * ((Ux(2:nx, 2:ny, 2:nz) - Ux(2:nx, 1:ny - 1, 2:nz)) + (Uy(2:nx, 2:ny, 2:nz) - Uy(1:nx - 1, 2:ny, 2:nz))));
end
